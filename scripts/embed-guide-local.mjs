import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { GUIDE_SCRIPTS } from '../client/src/features/learning/guides/inf1003/scripts.generated.js';

const assetRoot = new URL('../public/guides/inf1003/scripts/', import.meta.url);
const scripts = { ...GUIDE_SCRIPTS, meta: { ...GUIDE_SCRIPTS.meta } };
const hashes = {};
for (const name of ['01-start-cloudshell.sh', '03-clean-cloudshell.sh', 'start-aws-local.sh', 'start-aws-local.ps1']) {
  const source = readFileSync(new URL(name, assetRoot), 'utf8').replace(/\r\n/g, '\n');
  writeFileSync(new URL(name, assetRoot), source);
  hashes[name] = createHash('sha256').update(source).digest('hex');
  const key = name.startsWith('01-') ? 'start' : name.startsWith('03-') ? 'clean' : null;
  if (key) {
    scripts[key] = source;
    scripts.meta[key] = { ...scripts.meta[key], sha256: hashes[name], bytes: Buffer.byteLength(source) };
  }
}
const destination = new URL('../client/src/features/learning/guides/inf1003/', import.meta.url);
writeFileSync(new URL('scripts.generated.js', destination), '// Generated by scripts/embed-guide-local.mjs.\nexport const GUIDE_SCRIPTS = ' + JSON.stringify(scripts, null, 2) + ';\n');
writeFileSync(new URL('local-meta.generated.js', destination), '// Generated by scripts/embed-guide-local.mjs.\nexport const GUIDE_LOCAL_META = ' + JSON.stringify(hashes, null, 2) + ';\n');
